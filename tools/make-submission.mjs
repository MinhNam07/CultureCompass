#!/usr/bin/env node
/* Builds the CSCU9X5 submission folder from an allowlist: only what the prototype pages load.
   Nothing from the tooling (git, Vercel, build scripts, docs, plans, sources, editor files) can get in,
   because nothing is copied unless it is listed here.

     node tools/make-submission.mjs [outDir]      default outDir: ~/CultureCompass-submission

   Run `npm run build` first so the data files and the globe bundle are current.
   Result:
     <outDir>/30066857/website/              the site; open HomePage.html
     <outDir>/30066857/30066857_AI_Coversheet.docx   (copied from the template only if missing)
     <outDir>/30066857.zip                    the folder above, zipped
   The report PDF is added to <outDir>/30066857/ by hand; run the script again (or zip again) after that. */
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ID = '30066857';
const OUT = path.resolve(process.argv[2] || path.join(os.homedir(), 'CultureCompass-submission'));
const FOLDER = path.join(OUT, ID);
const SITE = path.join(FOLDER, 'website');

/* The pages of the prototype, and the two they open (the globe iframe, other countries from the HUD). */
const PAGES = ['HomePage.html', 'globe.html', 'explore.html', 'vietnam.html', 'story.html', 'collection.html', 'about.html', 'country-details.html'];

/* Folders copied whole (minus SKIP). Code and small media whose file names are composed at run time. */
const DIRS = [
  'vendor/bootstrap', 'vendor/gsap',
  'assets/css', 'assets/js', 'assets/globe', 'assets/tracing-beam', 'assets/fonts', 'assets/audio',
  'assets/data', 'assets/img',
  'assets/game/audio', 'assets/game/characters', 'assets/game/maps', 'assets/game/sprites', 'assets/game/tilesets',
];
/* Single files from the third-party packs: the two sheets every map draws from, and the licence. */
const FILES = [
  'assets/game/vendor/serene-village/Serene_Village_16x16.png',
  'assets/game/vendor/limezu-interiors-free/Interiors_free/16x16/Room_Builder_free_16x16.png',
  'assets/game/vendor/limezu-interiors-free/LICENSE.txt',
];
const SKIP = [
  /(^|\/)\.DS_Store$/, /(^|\/)Thumbs\.db$/,
  /^assets\/.*\.json$/,                  // data sources and sprite-sheet metadata: pages load .js, never JSON
  /(^|\/)README\.md$/,                    // notes for whoever edits the folder
  /^assets\/data\/vn-map\.js$/,          // used by the build only
  /^assets\/game\/maps\/.*\.tmj$/,       // Tiled sources of the map .js files
  /^assets\/js\/scene-engine\.js$/,      // no page loads it
  /^assets\/js\/country\.js$/,           // only the legacy compass page loaded it
];

const rel = (p) => path.relative(ROOT, p).split(path.sep).join('/');
function walk(dir, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out); else out.push(p);
  }
  return out;
}
function copy(r) {
  const to = path.join(SITE, r);
  mkdirSync(path.dirname(to), { recursive: true });
  cpSync(path.join(ROOT, r), to);
}

for (const need of ['assets/globe/globe.js', 'assets/data/stories.js']) {
  if (!existsSync(path.join(ROOT, need))) { console.error(`Missing ${need}: run npm run build first.`); process.exit(1); }
}
rmSync(SITE, { recursive: true, force: true });
mkdirSync(SITE, { recursive: true });

const files = [...PAGES, ...FILES];
for (const d of DIRS) for (const f of walk(path.join(ROOT, d))) files.push(rel(f));
const kept = files.filter((r) => !SKIP.some((re) => re.test(r)));
kept.forEach(copy);

/* Comments that name the build scripts point at files the submission does not contain; reword them in the copy
   (the repo keeps the originals). Generated headers become a plain note of where the file came from. */
const REWORD = [
  [/^\/\* GENERATED from (\S+)\.(?:json|tmj) by tools\/[\w./-]+\. Do not edit[^*]*\*\/\n/, '/* Generated from the $1 data. */\n'],
  [/Generated by tools\/media\/osm-to-svg\.mjs\. /, ''],
  [/, built by tools\/recolor-character\.py from LimeZu Modern Interiors/, ', recoloured from LimeZu Modern Interiors'],
  [/To add a character, add it to\n\s*assets\/game\/characters\/recolor\.json, run the tool, and add a line here\./, 'To add a character, add its sheets and a line here.'],
  [/ \(OpenStreetMap geometry, tools\/media\/osm-to-svg\.mjs\)/, ' (OpenStreetMap geometry)'],
  [/ Ship: tools\/pixel-rocket\/ship\.py; effects: beanfx sheets from\n\s*tools\/pixel-rocket\/fx\.py \(4 frames per row\)\./, ' Effects: beanfx sheets, 4 frames per row.'],
  [/Draws a Tiled map built by tools\/build-maps\.js \(CC\.maps\[id\]\)/, 'Draws a Tiled map converted to JavaScript (CC.maps[id])'],
];
for (const r of kept.filter((x) => /\.(js|css|html)$/.test(x) && !x.startsWith('vendor/') && !x.startsWith('assets/globe/') && !x.startsWith('assets/tracing-beam/'))) {
  const f = path.join(SITE, r);
  const before = readFileSync(f, 'utf8');
  const after = REWORD.reduce((t, [re, to]) => t.replace(re, to), before);
  if (after !== before) writeFileSync(f, after);
}

/* Videos are large, and a few are no longer used. Pages name a video by its id in the credits list (assets.json:
   "vid-…") or by its path; copy a video (and its poster) only if a page, a script or a data file other than the
   credits list itself names it. The legacy compass page's clip is named only by the script that page used. */
const TEXT = /\.(html|js|css)$/;
const corpus = kept.filter((r) => TEXT.test(r) && r !== 'assets/data/assets.js')
  .map((r) => readFileSync(path.join(ROOT, r), 'utf8')).join('\n');
const credits = JSON.parse(readFileSync(path.join(ROOT, 'assets/data/assets.json'), 'utf8')).assets || [];
const named = (needle) => new RegExp(`["'\`]${needle.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}["'\`]`).test(corpus);
const usedVideo = new Set();
for (const a of credits) {
  if (a.kind !== 'video') continue;
  if (named(a.id) || named(a.file)) { usedVideo.add(a.file); if (a.poster) usedVideo.add(a.poster); }
}
const videos = walk(path.join(ROOT, 'assets/video')).map(rel).filter((r) => !SKIP.some((re) => re.test(r)));
const leftOut = [];
for (const v of videos) {
  if (usedVideo.has(v) || corpus.includes(v)) { copy(v); kept.push(v); } else leftOut.push(v);
}

/* Check: every literal local path in the copied pages, scripts and styles exists in the submission. */
const shipped = new Set(kept);
const missing = new Set();
const PATH_RE = /(?:assets|vendor)\/[A-Za-z0-9_\-./ ]+?\.(?:png|jpe?g|webp|avif|svg|gif|ico|mp4|webm|m4a|mp3|ogg|woff2?|js|css|json)/g;
const pageRef = /(?:src|href|poster)\s*=\s*["']([^"'#?]+\.(?:html|css|js|png|jpe?g|webp|avif|svg|ico|mp4|webm))/g;
for (const r of kept.filter((x) => TEXT.test(x))) {
  const text = readFileSync(path.join(SITE, r), 'utf8');
  for (const m of text.matchAll(PATH_RE)) if (r !== 'assets/data/assets.js' && !shipped.has(m[0]) && !m[0].includes('-<') && existsSync(path.join(ROOT, m[0]))) missing.add(`${r}: ${m[0]}`);
  if (r.endsWith('.html')) for (const m of text.matchAll(pageRef)) {
    if (/^[a-z]+:/i.test(m[1])) continue;
    if (!existsSync(path.join(SITE, m[1]))) missing.add(`${r}: ${m[1]}`);
  }
}

/* Words that would point at infrastructure or tooling. Listed for a look; nothing is edited automatically. */
const FLAG = /tools\/|\bnpm\b|vercel|claude|anthropic|localhost|127\.0\.0\.1|\/Users\/|github\.com|\bTODO\b|\bFIXME\b/;
const flagged = [];
for (const r of kept.filter((x) => TEXT.test(x) && !x.startsWith('vendor/') && !x.startsWith('assets/globe/') && !x.startsWith('assets/tracing-beam/'))) {
  readFileSync(path.join(SITE, r), 'utf8').split('\n').forEach((line, i) => { if (FLAG.test(line)) flagged.push(`${r}:${i + 1}: ${line.trim().slice(0, 140)}`); });
}

const cover = path.join(FOLDER, `${ID}_AI_Coversheet.docx`);
const template = path.join(ROOT, 'report-plan/materials/COMPULSORY_CSCU9X5_coversheet_Template_SEPT-2026.docx');
if (!existsSync(cover) && existsSync(template)) cpSync(template, cover);

const zip = path.join(OUT, `${ID}.zip`);
rmSync(zip, { force: true });
execFileSync('zip', ['-r', '-X', '-q', zip, ID, '-x', '*.DS_Store', '__MACOSX/*'], { cwd: OUT });

const size = (p) => statSync(p).size;
const total = walk(SITE).reduce((n, f) => n + size(f), 0);
const report = [
  `Submission folder: ${FOLDER}`,
  `Website files: ${walk(SITE).length} (${(total / 1048576).toFixed(1)} MB)`,
  `Zip: ${zip} (${(size(zip) / 1048576).toFixed(1)} MB)`,
  `Videos left out (not used by any page): ${leftOut.join(', ') || 'none'}`,
  missing.size ? `MISSING (referenced but not copied):\n  ${[...missing].join('\n  ')}` : 'References: every literal local path is in the submission.',
  flagged.length ? `Lines to review (${flagged.length}):\n  ${flagged.join('\n  ')}` : 'No tools/npm/vercel/claude/localhost/github/TODO lines.',
].join('\n');
writeFileSync(path.join(OUT, 'last-build.txt'), report + '\n');
console.log(report);
if (missing.size) process.exit(1);
