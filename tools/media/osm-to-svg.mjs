// Turns an Overpass "out geom" JSON (streets, water, a few named buildings) into a small SVG map module.
//   node tools/media/osm-to-svg.mjs <osm.json[,more.json]> <out.js> <mapId>
// The output is a plain script (works from file://) that sets window.CC_MAPS[mapId] = { w, h, svg, streets: {name: {x, y}} }.
// Story map blocks name the map by mapId; the file goes in assets/data/maps/<mapId>.js.
// Map data © OpenStreetMap contributors, ODbL.
import { readFileSync, writeFileSync } from 'node:fs';

const [input, output, mapId = 'map'] = process.argv.slice(2);
// several inputs may be given, comma-separated (streets, then water)
const raw = input.split(',').flatMap((f) => JSON.parse(readFileSync(f, 'utf8')).elements);
// a multipolygon relation (a lake) becomes one closed ring: its outer ways stitched end to end
const stitch = (ways) => {
  const left = ways.map((w) => w.slice());
  const ring = left.shift() || [];
  const same = (a, b) => a.lat === b.lat && a.lon === b.lon;
  while (left.length) {
    const end = ring[ring.length - 1];
    const i = left.findIndex((w) => same(w[0], end) || same(w[w.length - 1], end));
    if (i === -1) { ring.push(...left.shift()); continue; }
    const w = left.splice(i, 1)[0];
    ring.push(...(same(w[0], end) ? w : w.reverse()).slice(1));
  }
  return ring;
};
const els = raw.map((e) => e.type === 'relation'
  ? { tags: e.tags || {}, geometry: stitch((e.members || []).filter((m) => m.role === 'outer' && m.geometry).map((m) => m.geometry)) }
  : e).filter((e) => e.tags && e.geometry && e.geometry.length > 1);

let minLat = Infinity, maxLat = -Infinity, minLon = Infinity, maxLon = -Infinity;
for (const e of els) if (e.tags.highway) for (const p of e.geometry) {
  minLat = Math.min(minLat, p.lat); maxLat = Math.max(maxLat, p.lat);
  minLon = Math.min(minLon, p.lon); maxLon = Math.max(maxLon, p.lon);
}
const k = Math.cos(((minLat + maxLat) / 2) * Math.PI / 180);
const W = 1000;
const sx = W / ((maxLon - minLon) * k);
const H = Math.round((maxLat - minLat) * sx);
const xy = (p) => [((p.lon - minLon) * k * sx).toFixed(1), ((maxLat - p.lat) * sx).toFixed(1)];
const d = (g, close) => 'M' + g.map((p) => xy(p).join(' ')).join('L') + (close ? 'Z' : '');
const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

const byName = {};
const parts = { water: [], minor: [], major: [], places: [] };
for (const e of els) {
  const t = e.tags;
  if (t.natural === 'water') { parts.water.push(`<path class="m-water" d="${d(e.geometry, true)}"/>`); continue; }
  if (t.building) { parts.places.push(`<path class="m-place" data-place="${esc(t.name)}" d="${d(e.geometry, true)}"/>`); continue; }
  const name = (t.name || '').replace(/^Phố /, '');
  const trade = /^Hàng /.test(name);
  const cls = trade ? 'm-trade' : /primary|secondary|tertiary/.test(t.highway) ? 'm-major' : 'm-minor';
  const path = `<path class="${cls}"${name ? ` data-street="${esc(name)}"` : ''} d="${d(e.geometry)}"/>`;
  (cls === 'm-minor' ? parts.minor : parts.major).push(path);
  if (name) (byName[name] = byName[name] || []).push(...e.geometry);
}
// a label point per street: the middle vertex of all its pieces
const streets = {};
for (const [name, pts] of Object.entries(byName)) {
  const p = pts[Math.floor(pts.length / 2)];
  const [x, y] = xy(p).map(Number);
  streets[name] = { x, y };
}
const svg = `<svg viewBox="0 0 ${W} ${H}" xmlns="http://www.w3.org/2000/svg">` +
  `<g class="m-waters">${parts.water.join('')}</g><g class="m-minors">${parts.minor.join('')}</g>` +
  `<g class="m-majors">${parts.major.join('')}</g><g class="m-places">${parts.places.join('')}</g></svg>`;
writeFileSync(output, `/* Generated by tools/media/osm-to-svg.mjs. Map data © OpenStreetMap contributors (ODbL). */\n(window.CC_MAPS = window.CC_MAPS || {})[${JSON.stringify(mapId)}] = ${JSON.stringify({ w: W, h: H, svg, streets })};\n`);
console.log(output, Math.round(svg.length / 1024) + 'KB', Object.keys(streets).length, 'named streets', W + 'x' + H);
