#!/usr/bin/env node
/* Builds the browser data files from the JSON content.
   Run `node tools/build-data.js` from the project root after editing assets/data/*.json.

   Why: pages load content with <script> tags so the site still works when index.html
   is opened straight from disk (browsers block fetch() on file://). Each JSON file is
   copied into a matching .js file that sets window.CC.<key> for every top-level key.
   Keys starting with "$" (such as "$comment") are notes for editors and are skipped.
   svgs.js is not generated: it holds SVG markup and is edited by hand. */
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dataDir = path.join(root, 'assets', 'data');
const FILES = ['sources', 'assets', 'phrases', 'scenarios', 'stories', 'topics', 'countries'];

function jsonPath(name) { return path.join(dataDir, name + '.json'); }
function jsPath(name) { return path.join(dataDir, name + '.js'); }

// Parses one JSON file; the error names the file and position.
function readJson(name) {
  const file = jsonPath(name);
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (e) {
    throw new Error(`${path.relative(root, file)}: ${e.message}`);
  }
}

// Returns the data from every JSON file merged into one object, like window.CC.
function loadAll() {
  const CC = {};
  for (const name of FILES) {
    const data = readJson(name);
    for (const key of Object.keys(data)) {
      if (key.startsWith('$')) continue;
      if (key in CC) throw new Error(`Key "${key}" is defined in more than one JSON file`);
      CC[key] = data[key];
    }
  }
  return CC;
}

// Returns the text of the generated .js file for one JSON file.
function render(name) {
  const data = readJson(name);
  const lines = [
    `/* GENERATED from ${name}.json by tools/build-data.js. Do not edit this file: edit the JSON and rebuild. */`,
    'window.CC = window.CC || {};'
  ];
  for (const key of Object.keys(data)) {
    if (key.startsWith('$')) continue;
    lines.push(`window.CC.${key} = ${JSON.stringify(data[key], null, 2)};`);
  }
  return lines.join('\n') + '\n';
}

// Lists the generated files that differ from what the JSON would produce.
function staleFiles() {
  return FILES.filter((name) => {
    const current = fs.existsSync(jsPath(name)) ? fs.readFileSync(jsPath(name), 'utf8') : '';
    return current !== render(name);
  });
}

function build() {
  for (const name of FILES) fs.writeFileSync(jsPath(name), render(name));
  return FILES.map((name) => `assets/data/${name}.js`);
}

module.exports = { FILES, loadAll, render, staleFiles };

if (require.main === module) {
  try {
    const written = build();
    console.log('Wrote ' + written.join(', '));
  } catch (e) {
    console.error('✗ ' + e.message);
    process.exit(1);
  }
}
