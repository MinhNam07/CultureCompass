// Turns assets/data/vn-map.js (made by tools/vn-map.py from Natural Earth, Vietnam point of view)
// into globe/hud/vn-map.generated.ts so the HUD on the homepage can draw the same map.
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync("assets/data/vn-map.js", "utf8");
const start = src.indexOf("CC.vnMap =");
if (start < 0) throw new Error("CC.vnMap not found in assets/data/vn-map.js");
const json = src.slice(start + "CC.vnMap =".length).trim().replace(/;\s*$/, "");
const map = JSON.parse(json);
const out = `// Generated by tools/build-hud-map.mjs from assets/data/vn-map.js. Do not edit by hand.
// Natural Earth 1:10m Admin 0 countries, Vietnam point of view (public domain).
export interface HudMapData { w: number; h: number; lon0: number; lat1: number; k: number; c: number; neighbours: { name: string; d: string }[]; vn: string; islets: [number, number][] }
export const vnMap: HudMapData = ${JSON.stringify({ w: map.w, h: map.h, lon0: map.lon0, lat1: map.lat1, k: map.k, c: map.c, neighbours: map.neighbours, vn: map.vn, islets: map.islets })};
`;
writeFileSync("globe/hud/vn-map.generated.ts", out);
console.log("globe/hud/vn-map.generated.ts written");
